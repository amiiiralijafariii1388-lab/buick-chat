create table if not exists public.rooms (
  room_code text primary key check (char_length(room_code) between 6 and 8),
  title text not null default 'گفتگوی بیوک',
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_code text not null references public.rooms(room_code) on delete cascade,
  text text not null check (char_length(text) between 1 and 2000),
  name text not null default 'کاربر بیوک',
  created_at timestamptz not null default now()
);

alter table public.rooms enable row level security;
alter table public.messages enable row level security;

drop policy if exists "prototype rooms readable" on public.rooms;
create policy "prototype rooms readable" on public.rooms
  for select to anon, authenticated using (true);

drop policy if exists "prototype rooms creatable" on public.rooms;
create policy "prototype rooms creatable" on public.rooms
  for insert to anon, authenticated with check (true);

drop policy if exists "prototype messages readable" on public.messages;
create policy "prototype messages readable" on public.messages
  for select to anon, authenticated using (true);

drop policy if exists "prototype messages creatable" on public.messages;
create policy "prototype messages creatable" on public.messages
  for insert to anon, authenticated with check (
    char_length(text) between 1 and 2000
    and char_length(room_code) between 6 and 8
    and char_length(name) between 1 and 40
  );

-- Enable Realtime for new messages (safe to run more than once).
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end $$;
